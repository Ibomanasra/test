const ORDER_STATUS: Record<Locale, Record<string, string>> = {
  ar: { NEW: "جديد", CONFIRMED: "مؤكد", PICKING: "قيد التجهيز", READY: "جاهز", OUT_FOR_DELIVERY: "في الطريق", DELIVERED: "تم التسليم", CANCELLED: "ملغى" },
  en: { NEW: "New", CONFIRMED: "Confirmed", PICKING: "Picking", READY: "Ready", OUT_FOR_DELIVERY: "Out for delivery", DELIVERED: "Delivered", CANCELLED: "Cancelled" },
};

export function translator(locale: Locale) {
  const dict = locale === "ar" ? ar : en;
  return {
    t: (key: MessageKey) => dict[key],
    status: (s: string) => ORDER_STATUS[locale][s] ?? s,
    /** Beträge immer mit lateinischen Ziffern (wie im Web) */
    money: (agorot: number) => formatMoney(agorot),
    pick: (o: { ar?: string | null; en?: string | null; nameAr?: string | null; nameEn?: string | null }) => (locale === "ar" ? (o.nameAr ?? o.ar ?? o.nameEn ?? o.en) : (o.nameEn ?? o.en ?? o.nameAr ?? o.ar)) ?? "",
  };
}

export function errorMessage(locale: Locale, err: unknown): string {
  const code = (err as { body?: { code?: string } })?.body?.code;
  if (code === "network") return translator(locale).t("networkError");
  const known: Record<string, [string, string]> = {
    invalid_code: ["الرمز غير صحيح", "Invalid code"],
    rate_limited: ["طلبات كثيرة، حاول لاحقاً", "Too many requests, try later"],
    invalid_credentials: ["رقم الهاتف أو كلمة المرور غير صحيحة", "Wrong phone or password"],
    insufficient_stock: ["الكمية غير متوفرة", "Not enough stock"],
    below_minimum_order: ["أقل من الحد الأدنى للطلب", "Below the minimum order"],
    credit_limit_exceeded: ["تجاوز حد الائتمان", "Credit limit exceeded"],
    cart_has_problems: ["راجع الكميات في السلة", "Please check the cart quantities"],
  };
  const m = code ? known[code] : undefined;
  return m ? m[locale === "ar" ? 0 : 1] : translator(locale).t("error");
}
